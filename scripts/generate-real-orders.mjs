// Build lib/realOrders.js from a parsed vendor name list.
//
//   python3 scripts/extract-namelist.py "<Name List>.pdf"
//   python3 scripts/parse-namelist.py          -> /tmp/namelist14.json
//   node    scripts/generate-real-orders.mjs 2026-09-14
//
// The sheet prints dish names clipped to the cell width ("RM12 - Dry Minced
// Chicken Noodle served"), so each label is resolved against that date's real
// menu by prefix instead of being trusted verbatim. An unresolved label is a
// hard error: guessing one would put the wrong meal on an invoice.

import { readFileSync, writeFileSync } from 'node:fs';
import { MENU_BY_DATE } from '../lib/menuData.js';

const iso = process.argv[2];
if (!iso) { console.error('usage: generate-real-orders.mjs <YYYY-MM-DD>'); process.exit(1); }

const rows = JSON.parse(readFileSync('/tmp/namelist14.json', 'utf8'));
const menu = MENU_BY_DATE[iso];
if (!menu) { console.error(`no menu for ${iso}`); process.exit(1); }

const CHEF = "Chef's Choice";

/// Resolve one printed label to a menu dish name, Chef's Choice, or null.
function resolve(label, slot) {
  if (!label) return null;
  if (/^Chef's Choice/.test(label)) return CHEF;
  const bare = label.replace(/^RM\d+\s*-\s*/, '').trim();
  const items = menu[slot] ?? [];
  // The label is a prefix of the real name, or the real name a prefix of it.
  const hit = items.find(i => {
    const a = i.name.toLowerCase(), b = bare.toLowerCase();
    return a.startsWith(b.slice(0, Math.min(b.length, 18))) || b.startsWith(a.slice(0, Math.min(a.length, 18)));
  });
  return hit ? hit.name : { unresolved: bare };
}

const YEAR_FIX = { PLUS: 'Cambridge Plus' };

// Rows whose name is missing from the PDF's text layer, resolved by hand.
//
// The 14 September sheet has two: a Cambridge Year 3 breakfast and a Cambridge
// Year 3 lunch. Peter John A. Pizon is the only Year 3 student on the roster
// absent from that sheet, and adding him to each column gives exactly the 42
// breakfast / 51 lunch the school counts — so the identification is by
// elimination, not from the file.
//
// Keyed `side|group|year`, which is all the sheet gives for such a row.
const UNNAMED_OVERRIDES = {
  '2026-09-14': {
    'breakfast|Cambridge|Year 3': 'Peter John A. Pizon',
    'lunch|Cambridge|Year 3': 'Peter John A. Pizon',
  },
};

// Resolve the nameless rows before anything else, and stop if any is unknown.
// Dropping them is what left a child with an egg allergy off the sheet.
const overrides = UNNAMED_OVERRIDES[iso] ?? {};
const unresolved = [];
for (const r of rows) {
  if (r.name) continue;
  const key = `${r.side}|${r.group}|${r.year}`;
  const name = overrides[key];
  if (!name) { unresolved.push(`${key}  (${r.dish})`); continue; }
  r.name = name;
}
if (unresolved.length) {
  console.error(`${unresolved.length} row(s) have no name and no override for ${iso}:`);
  for (const u of unresolved) console.error('  ' + u);
  console.error('Add them to UNNAMED_OVERRIDES in this script. Refusing to write a');
  console.error('sheet that silently omits someone.');
  process.exit(1);
}

const byPerson = new Map();
const problems = [];
for (const r of rows) {
  const key = r.name.trim();
  const rec = byPerson.get(key) ?? {
    name: key,
    dept: r.group || null,
    year: r.year ? (YEAR_FIX[r.year.toUpperCase()] ?? r.year) : null,
    breakfast: null, lunch: null, brunch: null,
  };
  const both = /^Chef's Choice \(Breakfast & Lunch\)/.test(r.dish);
  if (both) { rec.breakfast = CHEF; rec.lunch = CHEF; }
  else {
    const v = resolve(r.dish, r.side);
    if (v && v.unresolved) problems.push(`${key} / ${r.side}: ${v.unresolved}`);
    else rec[r.side] = v;
  }
  if (!rec.dept && r.group) rec.dept = r.group;
  if (!rec.year && r.year) rec.year = YEAR_FIX[r.year.toUpperCase()] ?? r.year;
  byPerson.set(key, rec);
}

if (problems.length) {
  console.error('UNRESOLVED dish labels — refusing to write:');
  for (const p of problems) console.error('  ' + p);
  process.exit(1);
}

const people = [...byPerson.values()].sort((a, b) => a.name.localeCompare(b.name));

const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "\\'")}'`);
const body = people.map(p =>
  `  { name: ${q(p.name)}, dept: ${q(p.dept)}, year: ${q(p.year)}, ` +
  `breakfast: ${q(p.breakfast)}, lunch: ${q(p.lunch)}, brunch: ${q(p.brunch)} },`
).join('\n');

const out = `// GENERATED by scripts/generate-real-orders.mjs — do not edit by hand.
//
// Orders taken from the school's own vendor name lists, which are the record of
// what was actually served. A date present here is used verbatim; dates absent
// from it still fall back to generated samples, so it is obvious in the vendor
// view which days are real.

export const REAL_ORDERS = {
  '${iso}': [
${body}
  ],
};

/// Dates with real orders on file.
export const REAL_DATES = new Set(Object.keys(REAL_ORDERS));
`;

writeFileSync(new URL('../lib/realOrders.js', import.meta.url), out);

const nb = people.filter(p => p.breakfast).length;
const nl = people.filter(p => p.lunch).length;
console.log(`${iso}: ${people.length} people — ${nb} breakfast, ${nl} lunch`);
console.log('wrote lib/realOrders.js');
